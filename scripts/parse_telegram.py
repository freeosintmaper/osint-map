def extract_media(block):
    photo_url = None
    video_url = None
    m = re.search(r"tgme_widget_message_photo_wrap[^>]*style=\"[^\"]*url\('([^']+)'\)", block)
    if not m:
        m = re.search(r"tgme_widget_message_photo[^>]*style=\"[^\"]*url\('([^']+)'\)", block)
    if m:
        photo_url = m.group(1)
    m = re.search(r'<video[^>]*src="([^"]+)"', block)
    if m:
        video_url = m.group(1)
    else:
        m = re.search(r"tgme_widget_message_video_thumb[^>]*style=\"[^\"]*url\('([^']+)'\)", block)
        if m:
            video_url = m.group(1)
    return photo_url, video_url


def extract_posts(html):
    posts = []
    blocks = re.split(r'<div class="tgme_widget_message_wrap[^"]*"', html)
    for block in blocks[1:]:
        date_match = re.search(r'<time datetime="([^"]+)"', block)
        date_str = date_match.group(1) if date_match else ""
        text_match = re.search(
            r'<div class="tgme_widget_message_text[^"]*"[^>]*>(.*?)</div>\s*</div>',
            block, re.DOTALL
        )
        if not text_match:
            continue
        text = text_match.group(1)
        text = re.sub(r'<br\s*/?>', '\n', text)
        text = re.sub(r'<[^>]+>', '', text)
        text = unescape(text).strip()
        id_match = re.search(r'data-post="([^"]+)"', block)
        url = f"https://t.me/{id_match.group(1)}" if id_match else ""
        photo_url, video_url = extract_media(block)
        if len(text) > 20:
            posts.append({
                "text": text, "date": date_str, "url": url,
                "photo_url": photo_url, "video_url": video_url
            })
    return posts


def _find_bounded_word(text_lower, phrase_lower):
    """Ищет phrase как ОТДЕЛЬНОЕ слово (не подстроку).
    'александров' НЕ найдётся внутри 'александровку'.
    'чита' НЕ найдётся внутри 'считается'.
    """
    pattern = rf'(?<![а-яёa-z0-9]){re.escape(phrase_lower)}(?![а-яёa-z0-9])'
    m = re.search(pattern, text_lower)
    return m.start() if m else -1


def _word_in_text(text_lower, phrase_lower):
    """Проверка: есть ли phrase как отдельное слово в text."""
    return _find_bounded_word(text_lower, phrase_lower) >= 0


