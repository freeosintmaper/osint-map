if __name__ == "__main__":
    clf = LLMClassifier()
    if clf.client is None:
        print("❌ LLM не инициализирован — проверьте секреты")
        raise SystemExit(1)
    for i, text in enumerate(POSTS, 1):
        print(f"\n{'='*60}")
        print(f"Пост {i}: {text[:100]}...")
        result = clf.classify(text)
        print(f"Результат: {result}")
